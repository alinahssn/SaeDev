package universite_paris8.iut.aulhassan.maphopital.modele.Ennemi;

public class MouchoirEnrhumé {

    private int x;
    private int y;

    public MouchoirEnrhumé(int x, int y) {
        this.x = x;
        this.y = y;
    }

    public int getX() {
        return x;
    }

    public int getY() {
        return y;
    }
}
